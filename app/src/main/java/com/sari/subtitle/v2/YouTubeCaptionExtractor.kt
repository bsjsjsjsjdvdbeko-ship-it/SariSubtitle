package com.sari.subtitle.v2

import android.net.Uri
import org.json.JSONObject
import org.xmlpull.v1.XmlPullParser
import org.xmlpull.v1.XmlPullParserFactory
import java.io.ByteArrayInputStream
import java.io.IOException
import java.net.HttpURLConnection
import java.net.URL
import java.util.Locale

/**
 * Extracts publicly exposed YouTube caption tracks from a watch page.
 * This does not download video/audio and only works when YouTube exposes captions
 * to an unauthenticated watch-page request. It is not a universal social-media extractor.
 */
object YouTubeCaptionExtractor {
    data class Track(val languageCode: String, val name: String, val baseUrl: String, val isAutoGenerated: Boolean)
    data class Result(val srt: String, val languageCode: String, val cueCount: Int, val autoGenerated: Boolean)

    fun extract(videoUrl: String, requestedLanguage: String = "auto"): Result {
        val videoId = getVideoId(videoUrl) ?: throw IOException("لم أستطع استخراج معرّف فيديو YouTube من الرابط.")
        val page = request("https://www.youtube.com/watch?v=$videoId", 8 * 1024 * 1024)
        val playerJson = findJsonAssignment(page, "ytInitialPlayerResponse")
            ?: throw IOException("لم يكشف YouTube بيانات المشغّل. قد يكون الفيديو خاصاً أو يتطلب تسجيل الدخول أو التحقق.")
        val root = try { JSONObject(playerJson) } catch (_: Exception) {
            throw IOException("تعذر تحليل بيانات فيديو YouTube.")
        }
        val renderer = root.optJSONObject("captions")
            ?.optJSONObject("playerCaptionsTracklistRenderer")
            ?: throw IOException("لم يتم العثور على مسارات ترجمة متاحة لهذا الفيديو.")
        val tracksJson = renderer.optJSONArray("captionTracks")
            ?: throw IOException("هذا الفيديو لا يعرض مسارات ترجمة قابلة للاستخراج.")
        val tracks = mutableListOf<Track>()
        for (i in 0 until tracksJson.length()) {
            val item = tracksJson.optJSONObject(i) ?: continue
            val baseUrl = item.optString("baseUrl").takeIf { it.startsWith("https://") } ?: continue
            val lang = item.optString("languageCode")
            if (lang.isBlank()) continue
            val name = item.optJSONObject("name")?.optString("simpleText")
                ?: item.optJSONObject("name")?.optJSONArray("runs")?.optJSONObject(0)?.optString("text")
                ?: lang
            tracks += Track(lang, name, baseUrl, item.optString("kind") == "asr")
        }
        if (tracks.isEmpty()) throw IOException("لم يعثر YouTube على أي مسار ترجمة متاح.")

        val selected = when (requestedLanguage.lowercase(Locale.ROOT)) {
            "ar" -> tracks.firstOrNull { it.languageCode.equals("ar", true) }
                ?: tracks.firstOrNull { it.languageCode.startsWith("ar-") }
            "en" -> tracks.firstOrNull { it.languageCode.equals("en", true) }
                ?: tracks.firstOrNull { it.languageCode.startsWith("en-") }
            else -> tracks.firstOrNull { it.languageCode.equals("en", true) }
                ?: tracks.firstOrNull { it.languageCode.equals("ar", true) }
                ?: tracks.first()
        } ?: throw IOException("لا توجد ترجمة بلغة ${if (requestedLanguage == "ar") "العربية" else "الإنجليزية"}. اللغات المتاحة: ${tracks.joinToString { it.languageCode }}")

        val xml = request(selected.baseUrl, 5 * 1024 * 1024)
        val srt = xmlToSrt(xml)
        val count = SrtParser.parse(srt.byteInputStream(Charsets.UTF_8)).size
        if (count == 0) throw IOException("تم الوصول إلى مسار الترجمة، لكنه لم يحتوِ على مقاطع قابلة للتحويل.")
        return Result(srt, selected.languageCode, count, selected.isAutoGenerated)
    }

    fun getVideoId(raw: String): String? {
        val uri = try { Uri.parse(raw.trim()) } catch (_: Exception) { return null }
        val host = uri.host?.lowercase(Locale.ROOT)?.removePrefix("www.") ?: return null
        return when {
            host == "youtu.be" -> uri.pathSegments.firstOrNull()?.takeIf { it.matches(Regex("[A-Za-z0-9_-]{11}")) }
            host == "youtube.com" || host.endsWith(".youtube.com") -> {
                val v = uri.getQueryParameter("v")
                if (!v.isNullOrBlank() && v.matches(Regex("[A-Za-z0-9_-]{11}"))) v
                else {
                    val parts = uri.pathSegments
                    val candidate = when {
                        parts.size >= 2 && parts[0] in setOf("embed", "shorts", "live", "v") -> parts[1]
                        else -> null
                    }
                    candidate?.takeIf { it.matches(Regex("[A-Za-z0-9_-]{11}")) }
                }
            }
            else -> null
        }
    }

    private fun request(url: String, maxBytes: Int): String {
        var connection: HttpURLConnection? = null
        try {
            connection = (URL(url).openConnection() as HttpURLConnection).apply {
                connectTimeout = 15_000
                readTimeout = 25_000
                instanceFollowRedirects = true
                setRequestProperty("User-Agent", "Mozilla/5.0 (Linux; Android 13) AppleWebKit/537.36 Chrome/124.0.0.0 Mobile Safari/537.36")
                setRequestProperty("Accept-Language", "en-US,en;q=0.9,ar;q=0.8")
            }
            val code = connection.responseCode
            if (code !in 200..299) throw IOException("رد YouTube برمز HTTP $code.")
            val length = connection.contentLengthLong
            if (length > maxBytes) throw IOException("استجابة YouTube أكبر من الحد الآمن.")
            val bytes = connection.inputStream.use { input ->
                val out = java.io.ByteArrayOutputStream()
                val buffer = ByteArray(8192)
                var total = 0
                while (true) {
                    val n = input.read(buffer)
                    if (n < 0) break
                    total += n
                    if (total > maxBytes) throw IOException("تم إيقاف الطلب لأن الاستجابة تجاوزت الحد الآمن.")
                    out.write(buffer, 0, n)
                }
                out.toByteArray()
            }
            return String(bytes, Charsets.UTF_8)
        } finally {
            connection?.disconnect()
        }
    }

    /** Extracts a balanced JSON object assigned to a JavaScript variable. */
    private fun findJsonAssignment(html: String, variable: String): String? {
        val marker = Regex("(?:var\\s+|let\\s+|const\\s+)?" + Regex.escape(variable) + "\\s*=").find(html) ?: return null
        val start = html.indexOf('{', marker.range.last + 1)
        if (start < 0) return null
        var depth = 0
        var inString = false
        var escaped = false
        for (i in start until html.length) {
            val c = html[i]
            if (inString) {
                if (escaped) escaped = false
                else if (c == '\\') escaped = true
                else if (c == '"') inString = false
                continue
            }
            when (c) {
                '"' -> inString = true
                '{' -> depth++
                '}' -> {
                    depth--
                    if (depth == 0) return html.substring(start, i + 1)
                }
            }
        }
        return null
    }

    private fun xmlToSrt(xml: String): String {
        val factory = XmlPullParserFactory.newInstance()
        factory.isNamespaceAware = false
        val parser = factory.newPullParser()
        parser.setInput(ByteArrayInputStream(xml.toByteArray(Charsets.UTF_8)), "UTF-8")
        val cues = mutableListOf<SubtitleCue>()
        var event = parser.eventType
        var index = 1
        while (event != XmlPullParser.END_DOCUMENT) {
            if (event == XmlPullParser.START_TAG && parser.name == "text") {
                val startSec = parser.getAttributeValue(null, "start")?.toDoubleOrNull()
                val durationSec = parser.getAttributeValue(null, "dur")?.toDoubleOrNull()
                val rawText = try { parser.nextText() } catch (_: Exception) { "" }
                val text = rawText
                    .replace("<br />", "\n", true)
                    .replace(Regex("<[^>]+>"), "")
                    .replace("&nbsp;", " ")
                    .trim()
                if (startSec != null && text.isNotBlank()) {
                    val startMs = (startSec * 1000).toLong().coerceAtLeast(0L)
                    val endMs = startMs + ((durationSec ?: 2.0) * 1000).toLong().coerceAtLeast(500L)
                    cues += SubtitleCue(index++, startMs, maxOf(startMs + 250, endMs), text)
                }
            }
            event = parser.eventType
            if (event != XmlPullParser.END_DOCUMENT) event = parser.next()
        }
        if (cues.isEmpty()) throw IOException("مسار الترجمة لم يُرجع مقاطع نصية مع توقيتات.")
        return cues.joinToString("\n\n") { cue ->
            "${cue.index}\n${timestamp(cue.startMs)} --> ${timestamp(cue.endMs)}\n${cue.text}"
        } + "\n"
    }

    private fun timestamp(ms: Long): String {
        val total = ms.coerceAtLeast(0)
        val hours = total / 3_600_000
        val minutes = (total % 3_600_000) / 60_000
        val seconds = (total % 60_000) / 1000
        val millis = total % 1000
        return String.format(Locale.US, "%02d:%02d:%02d,%03d", hours, minutes, seconds, millis)
    }
}
